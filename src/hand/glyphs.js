const A = (cx, cy, rx, ry, a0, a1, step = 15) => {
  const out = [], n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / step));
  for (let i = 0; i <= n; i++) { const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180; out.push(cx + rx * Math.cos(a), cy + ry * Math.sin(a)); }
  return out;
};
