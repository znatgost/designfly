export const GAP = 2.4, SPACE = 5;

/** text → normalised character list the alphabet can draw */
export function glyphText(text) {
  const s = String(text).normalize('NFC').toUpperCase().replace(/Й/g, '\u0001').replace(/Ё/g, '\u0002')
    .normalize('NFD').replace(/[̀-ͯ]/g, '').normalize('NFC').replace(/\u0001/g, 'Й').replace(/\u0002/g, 'Ё').replace(/ß/g, 'SS');
  return [...s]
    .map((c) => (GLYPHS[c] ? c :/\s/.test(c) ? ' ' : c === '’' || c === '‘' ? "'" : c === '“' || c === '”' || c === '«' || c === '»' ? '"' : c === '—' ? '–' : null))
    .filter((c) => c !== null);
}
/** can the fly letter this by hand? (its alphabet is Latin + Cyrillic) */
export function canLetter(text) {
  const all = [...String(text)].filter((c) => /[\p{L}\p{N}]/u.test(c));
  if (!all.length) return true;
  return glyphText(all.join('')).length >= all.length * 0.75;
}
/** width of a text in grid units (cap height = 10) */
export function textUnits(text, track = 0) {
  const cs = glyphText(text);
  let w = 0;
  cs.forEach((c, i) => { w += c === ' ' ? SPACE : GLYPHS[c].w; if (i < cs.length - 1) w += GAP + track; });
  return w;
}
